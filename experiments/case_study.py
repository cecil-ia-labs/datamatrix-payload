"""Build the 16-state RfD case study and the local app's state catalogue."""
from __future__ import annotations
import base64
import hashlib
import json
import platform
from pathlib import Path

import numpy as np
import PIL

from qddm import (
    AUTHORS, TITLE, DEFAULT_PALETTE, encode, decode, inspect,
    single_frame_gif, scalar_to_hex, scalar_to_dimensions,
)

ROOT = Path(__file__).resolve().parents[1]
SEED = 20261104

def main():
    rng = np.random.default_rng(SEED)
    original = rng.integers(0, 256, 16 * 3072, dtype=np.uint8).tobytes()
    palettes = [DEFAULT_PALETTE[i:] + DEFAULT_PALETTE[:i] for i in range(16)]
    encoded = encode(original.hex(), frames=16, palettes=palettes)
    recovered = bytes.fromhex(decode(encoded.gif, payload_bytes=len(original)))
    assert recovered == original
    frames = inspect(encoded.gif)
    artifact = ROOT / "examples/quad-dimensional-datamatrix-16-states.gif"
    artifact.write_bytes(encoded.gif)
    states = []
    for i, frame in enumerate(frames):
        raw_state = single_frame_gif(frame)
        code_hex = decode(raw_state)
        assert code_hex == original[i * 3072:(i + 1) * 3072].hex().upper()
        states.append(dict(index_hex=f"0x{i:02X}", code_hex=code_hex,
                           gif_base64=base64.b64encode(raw_state).decode("ascii")))
    (ROOT / "examples/state-data.js").write_text(
        "// Generated by experiments/case_study.py; public synthetic study data.\n"
        "export const states = " + json.dumps(states, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    samples = []
    for character in ("A", "ã", "€", "😀"):
        value = ord(character)
        samples.append(dict(character=character, unicode_scalar_hex=scalar_to_hex(value),
                            utf8_hex=character.encode("utf-8").hex().upper(),
                            dimension_hex=scalar_to_dimensions(value)))
    report = dict(
        title=TITLE, status="Request for Discussion", version="0.2.0",
        authors=AUTHORS, language_default="en", language_alternative="pt",
        seed=SEED, python=platform.python_version(), numpy=np.__version__,
        Pillow=PIL.__version__,
        profile=dict(format="indexed GIF", pixel_side=256, effective_side=64,
                     pixels_per_module_side=4, maximum_palette_entries=64,
                     maximum_frames=64),
        catalogue=dict(full_tuple_count=64**4, full_cycle_seconds_at_8_fps=8,
                       candidate_tuples_per_second=64**4//8,
                       selected_modules_per_full_cycle=64**3,
                       full_cycle_payload_bits=64**3*6,
                       full_cycle_payload_bytes=64**3*6//8,
                       payload_bytes_per_second_at_8_fps=64*64*6*8//8),
        case_study=dict(frames=len(frames), colors_per_state=64,
                        duration_ms=sum(f.delay_cs for f in frames)*10,
                        payload_bytes=len(original), gif_file_bytes=len(encoded.gif),
                        payload_sha256=hashlib.sha256(original).hexdigest(),
                        recovered_sha256=hashlib.sha256(recovered).hexdigest(),
                        gif_sha256=hashlib.sha256(encoded.gif).hexdigest(),
                        exact_recovery=True,
                        artifact=artifact.relative_to(ROOT).as_posix(),
                        palette_hex_per_state=[f.palette_hex for f in frames]),
        unicode=dict(code_point_positions=0x110000, excluded_surrogate_positions=0x800,
                     scalar_values=0x110000-0x800, examples=samples),
        app=dict(sequence_location="application", default_state_period_ms=60000,
                 selection="pause the displayed state and copy its hexadecimal code",
                 copied_code="full state payload in hexadecimal",
                 state_count=len(states), authentication_status="discussion only"),
    )
    (ROOT / "results/hex-gif-case-study.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key:report[key] for key in ("title","catalogue","case_study") if key!="case_study"}))
    print(json.dumps({key:value for key,value in report["case_study"].items()
                      if key!="palette_hex_per_state"}))

if __name__ == "__main__":
    main()

