"""Integration checks for the DataMatrix attribution trial."""
import json
from pathlib import Path
import sys
import unittest

try:
    import tomllib
except ImportError:  # The reusable header tool also supports Python 3.10.
    tomllib = None

HERE = Path(__file__).resolve()
ROOT = HERE.parents[3]
AUTHORS_DIR = ROOT / "tools" / "authorship"
sys.path.insert(0, str(AUTHORS_DIR))
import authorship_headers as headers  # noqa: E402


class DataMatrixIntegrationTests(unittest.TestCase):
    def test_state_data_template_matches_checked_in_artifact(self):
        template = (AUTHORS_DIR / "templates/generated-state-data.header.txt").read_text(
            encoding="utf-8"
        )
        with (ROOT / "examples/state-data.js").open(encoding="utf-8") as stream:
            prefix = stream.read(len(template) + 120)
        self.assertTrue(
            prefix.startswith(template.rstrip("\n") + "\n\n"
                              + "// Generated by experiments/case_study.py;"),
            "The generated JS must use the same SPDX header as its source template.",
        )
        generator = (ROOT / "experiments/case_study.py").read_text(encoding="utf-8")
        self.assertIn("STATE_DATA_HEADER", generator)
        self.assertIn('STATE_DATA_HEADER + "\\n\\n"', generator)

    def test_scoped_author_rules_and_external_opt_out(self):
        p = AUTHORS_DIR / "attribution-policy.json"
        policy = json.loads(p.read_text(encoding="utf-8"))
        self.assertEqual(policy["version"], 1)
        args = headers.parse_args([
            str(ROOT), "--holder", "Cecil-IA Labs", "--author", "Default author",
            "--organization", "Cecil-IA Labs", "--license", "MIT", "--year", "2026",
            "--policy", str(p),
        ])
        self.assertIn("Jorge Luiz Espanhol",
                      headers.scoped_args(ROOT / "paper/quad-dimensional-datamatrix.en.md", args).author)
        self.assertEqual(headers.scoped_args(ROOT / "src/qddm/hexgif.py", args).author,
                         "Cecil-IA Labs project contributors")
        self.assertIsNone(headers.scoped_args(ROOT / "third_party/lib.c", args))
        self.assertIsNone(headers.scoped_args(ROOT / "examples/state-data.js", args))
        self.assertEqual(headers.scoped_args(ROOT / "README.md", args).author,
                         "Default author")

    @unittest.skipIf(tomllib is None, "Requires Python 3.11+ for TOML syntax test")
    def test_reuse_metadata_license_and_coverage(self):
        data = tomllib.loads((ROOT / "REUSE.toml").read_text(encoding="utf-8"))
        self.assertEqual(data["version"], 1)
        license_bytes = (ROOT / "LICENSE").read_bytes()
        self.assertEqual(license_bytes, (ROOT / "LICENSES/MIT.txt").read_bytes())
        tracked_patterns = [
            p for a in data["annotations"] for p in (
                a["path"] if isinstance(a["path"], list) else [a["path"]]
            )
        ]
        self.assertIn("paper/quad-dimensional-datamatrix.en.tex", tracked_patterns)
        self.assertIn("paper/quad-dimensional-datamatrix.en.pdf", tracked_patterns)
        self.assertIn("examples/quad-dimensional-datamatrix-16-states.gif",
                      tracked_patterns)
        self.assertIn("results/*.json", tracked_patterns)
        self.assertTrue(all(a["SPDX-License-Identifier"] == "MIT"
                            for a in data["annotations"]))

    def test_original_coauthor_and_license_untouched(self):
        citation = (ROOT / "CITATION.cff").read_text(encoding="utf-8")
        self.assertIn("João Paulo De Luca", citation)
        self.assertIn("Jorge Luiz Espanhol", citation)
        self.assertTrue((ROOT / "LICENSE").read_text(encoding="utf-8").startswith(
            "MIT License\n"
        ))


if __name__ == "__main__":
    unittest.main()
